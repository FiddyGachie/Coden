/**
 * T3.7 — Render & Persist
 *
 * Renders CONSTITUTION.md (human-readable) and
 * .warden/constitution.rules.json (machine-readable) from a set of
 * approved/proposed rules.
 *
 * SPEC §5.5: The JSON includes the SHA-256 of CONSTITUTION.md and every
 * source doc hash. Round-trip: render → parse JSON → hashes verify.
 */
import { createHash } from "node:crypto";
import { writeFile, mkdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import type { IngestedDoc } from "./doc-ingestion.js";

// ── Rule type for rendering ───────────────────────────────────────────────────
// (Subset of the full Rule schema; the full schema lives in @warden/shared)

export type RenderableRule = {
  id: string;
  title: string;
  severity: "info" | "warn" | "error" | "critical";
  /** "forbidden-call" | "import-boundary" | … */
  checker: string;
  params: Record<string, unknown>;
  remediation: string;
  status: "proposed" | "approved" | "disabled";
  /** Source attribution. */
  source: {
    file: string;
    startLine?: number;
    endLine?: number;
    quote?: string;
  };
};

export type ConstitutionMeta = {
  projectName: string;
  version: number;
  generatedAt: string;
  /** Map of doc path → SHA-256 hash. */
  sourceHashes: Record<string, string>;
};

export type ConstitutionJson = {
  meta: ConstitutionMeta;
  /** SHA-256 of the rendered CONSTITUTION.md. */
  constitutionMdHash: string;
  rules: RenderableRule[];
};

// ── SHA-256 helper ────────────────────────────────────────────────────────────

export const sha256 = (content: string): string =>
  createHash("sha256").update(content, "utf8").digest("hex");

// ── Markdown renderer ─────────────────────────────────────────────────────────

/**
 * Render the human-readable CONSTITUTION.md from rules and doc metadata.
 * Format follows SPEC §5.5.
 */
export const renderConstitutionMd = (
  rules: RenderableRule[],
  meta: ConstitutionMeta
): string => {
  const sourceList = Object.entries(meta.sourceHashes)
    .map(([path, hash]) => `${path}@${hash.slice(0, 12)}`)
    .join(", ");

  const approvedRules = rules.filter((r) => r.status === "approved");
  const proposedRules = rules.filter((r) => r.status === "proposed");

  const renderRule = (rule: RenderableRule): string => {
    const sourceRef = rule.source.startLine
      ? `${rule.source.file}:${rule.source.startLine}`
      : rule.source.file;
    const quoteLine = rule.source.quote ? `\n  > "${rule.source.quote}"` : "";
    return [
      `### ${rule.id} — ${rule.title}`,
      ``,
      `- **Severity:** ${rule.severity}`,
      `- **Checker:** \`${rule.checker}\``,
      `- **Status:** ${rule.status}`,
      `- **Source:** ${sourceRef}${quoteLine}`,
      ``,
      `**Remediation:** ${rule.remediation}`,
      ``
    ].join("\n");
  };

  const sections: string[] = [
    `# Constitution — ${meta.projectName}`,
    ``,
    `Generated by Warden · version ${meta.version} · ${meta.generatedAt}`,
    `Sources: ${sourceList || "(none)"}`,
    ``
  ];

  if (approvedRules.length > 0) {
    sections.push(`## Approved Rules (${approvedRules.length})`, ``);
    for (const rule of approvedRules) {
      sections.push(renderRule(rule));
    }
  }

  if (proposedRules.length > 0) {
    sections.push(`## Proposed Rules (${proposedRules.length})`, ``);
    sections.push(
      `> These rules are pending approval. They are not yet enforced.`,
      ``
    );
    for (const rule of proposedRules) {
      sections.push(renderRule(rule));
    }
  }

  if (approvedRules.length === 0 && proposedRules.length === 0) {
    sections.push(`*No rules defined yet.*`, ``);
  }

  return sections.join("\n");
};

// ── JSON builder ──────────────────────────────────────────────────────────────

export const buildConstitutionJson = (
  rules: RenderableRule[],
  meta: ConstitutionMeta,
  constitutionMd: string
): ConstitutionJson => ({
  meta,
  constitutionMdHash: sha256(constitutionMd),
  rules
});

// ── Persist to disk ───────────────────────────────────────────────────────────

export type PersistOptions = {
  /** Project root directory. */
  projectRoot: string;
  /** Path for CONSTITUTION.md relative to projectRoot. Default: "CONSTITUTION.md". */
  mdPath?: string;
  /** Path for the JSON file relative to projectRoot. Default: ".warden/constitution.rules.json". */
  jsonPath?: string;
};

export type PersistResult = {
  mdPath: string;
  jsonPath: string;
  mdHash: string;
  jsonHash: string;
};

export const persistConstitution = async (
  rules: RenderableRule[],
  meta: ConstitutionMeta,
  opts: PersistOptions
): Promise<PersistResult> => {
  const mdRelPath = opts.mdPath ?? "CONSTITUTION.md";
  const jsonRelPath = opts.jsonPath ?? ".warden/constitution.rules.json";

  const mdAbsPath = join(opts.projectRoot, mdRelPath);
  const jsonAbsPath = join(opts.projectRoot, jsonRelPath);

  const md = renderConstitutionMd(rules, meta);
  const json = buildConstitutionJson(rules, meta, md);
  const jsonStr = JSON.stringify(json, null, 2);

  // Ensure directories exist
  await mkdir(dirname(mdAbsPath), { recursive: true });
  await mkdir(dirname(jsonAbsPath), { recursive: true });

  await writeFile(mdAbsPath, md, "utf8");
  await writeFile(jsonAbsPath, jsonStr, "utf8");

  return {
    mdPath: mdAbsPath,
    jsonPath: jsonAbsPath,
    mdHash: sha256(md),
    jsonHash: sha256(jsonStr)
  };
};

// ── Source hash builder ───────────────────────────────────────────────────────

/** Build the sourceHashes map from ingested docs. */
export const buildSourceHashes = (docs: IngestedDoc[]): Record<string, string> =>
  Object.fromEntries(docs.map((d) => [d.name, d.hash]));
